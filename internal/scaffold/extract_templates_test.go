// One-shot extractor, run by hand to move a batch of templates out of Go string
// literals and into files:
//
//	go test ./internal/scaffold/ -run TestExtractTemplates -extract
//
// It is skipped without the flag, so an ordinary test run never writes to the
// repository.
//
// Not one-shot: the next directory moves the same way, by adding its functions
// to the map below and running this once. Re-running it over a batch that has
// already moved is a no-op, because those functions now read the files it would
// write.
//
// Two things to get right, both learned the hard way on this batch. Extract
// before rewriting the functions, or the extractor reads what it just wrote.
// And never put the output through gofmt: the scaffolder formats on the way
// out, and formatting here means substituting something for {{MODULE}}, which
// sorts to a different place in the import block than a real module path.
var extract = os.Getenv("GRIT_EXTRACT_TEMPLATES") != ""

// handlerTemplates is the batch being moved: everything written into a
