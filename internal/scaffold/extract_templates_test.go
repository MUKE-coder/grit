func TestExtractTemplates(t *testing.T) {
	if !extract {
		t.Skip("set GRIT_EXTRACT_TEMPLATES=1 to write the template files")
	}
	for name, fn := range handlerTemplates {
		path := filepath.Join("templates", name+".tmpl")
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		// One trailing newline, because a file has one and the literal did
		// not. tmpl() trims it back off so the generated bytes do not change.
		if err := os.WriteFile(path, []byte(fn()+"\n"), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", path)
	}
}
