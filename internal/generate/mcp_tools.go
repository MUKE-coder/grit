// MCP tools for a generated resource.
//
// Written only when the mcp plugin is installed, and self-registering: the
// file's own init() calls mcp.Register, so there is no marker to inject at and
// nothing to unpick. `grit remove resource` deletes the file and that is the
// whole removal, which is the property the generator's injection anchors keep
// failing to have. grit#224 proposed a `// grit:mcp-tools` marker; the registry
// already made one unnecessary.
//
// Five tools per resource, named for what a model would ask for rather than
// for the HTTP verb: list_invoices, get_invoice, create_invoice,
// update_invoice, delete_invoice.

// mcpToolsPath is where a resource's tools live, or "" when the project has no
// mcp package to register into.
//
// The gate is the package existing rather than a flag in grit.json, for the
// same reason every other optional thing is probed on disk: a project that
// installed the plugin and then removed it has the flag either way, and the
// question that matters is whether the import would compile.
func (g *Generator) mcpToolsPath() string {
	pkg := filepath.Join(g.APIRoot(), "internal", "mcp", "tool.go")
	if _, err := os.Stat(pkg); err != nil {
		return ""
	}
	return filepath.Join(g.APIRoot(), "internal", "mcp",
		"tools_"+g.Names().PluralSnake+".go")
}

// writeMCPTools emits the resource's tools file.
func (g *Generator) writeMCPTools() (string, error) {
	path := g.mcpToolsPath()
	if path == "" {
		return "", nil
	}
	if err := writeFileWithDirs(path, g.mcpToolsSource()); err != nil {
		return "", err
	}
	return path, nil
}

// mcpToolsSource is the file.
func (g *Generator) mcpToolsSource() string {
	n := g.Names()
	plural := n.PluralSnake
	single := n.Snake
	base := "/api/v1/" + n.PluralKebab
	label := strings.ToLower(humanizeLabel(n.Pascal))
	labels := strings.ToLower(humanizeLabel(n.PluralPascal))

	var b strings.Builder
	fmt.Fprintf(&b, `package mcp

// Tools for %s. Generated by grit generate resource; regenerated by grit sync.
//
// Self-registering: the init below hands them to the registry, so nothing
// imports this file and removing the resource is deleting it.
//
// Your own tools for %s go in custom_tools.go, which is never rewritten. The
// five here are the base, not the ceiling: the interesting tools in any app
// are the ones that are not create-read-update-delete.

import (
	"context"
	"fmt"
)

func init() {
	Register(
`, n.PluralPascal, labels)

	b.WriteString(g.mcpListTool(label, labels, plural, base))
	b.WriteString(g.mcpGetTool(label, single, plural, base))
	b.WriteString(g.mcpCreateTool(label, single, plural, base))
	b.WriteString(g.mcpUpdateTool(label, single, plural, base))
	b.WriteString(g.mcpDeleteTool(label, single, plural, base))

	// init closes before the shared body builder, which is a top-level
	// function and cannot sit inside Register's argument list.
	b.WriteString("\t)\n}\n")
	b.WriteString(g.mcpBodyBuilder())
	return b.String()
}

func (g *Generator) mcpListTool(label, labels, plural, base string) string {
	n := g.Names()

	props := []string{
		`"search": map[string]any{"type": "string", "description": "Match against the searchable text."}`,
		`"page": map[string]any{"type": "integer", "description": "1-based. Default 1."}`,
		`"page_size": map[string]any{"type": "integer", "description": "Default 20, capped at 100."}`,
		`"sort": map[string]any{"type": "string", "description": "A field name, prefixed with - for descending."}`,
	}
	for _, f := range g.filterableForMCP() {
		props = append(props, fmt.Sprintf(`%q: %s`, f.Name, g.mcpFieldSchema(f, false)))
	}

	return fmt.Sprintf(`		Tool{
			Name:  "list_%s",
			Title: "List %s",
			Description: "Search and page through %s. Returns the rows and the " +
				"pagination meta, so ask for a page rather than everything.",
			Group:      %q,
			Permission: %q,
			Routes:     []string{"GET %s"},
			Schema: map[string]any{
				"type": "object",
				"properties": map[string]any{
%s
				},
			},
			Exec: func(ctx context.Context, call *Call, args map[string]any) (any, error) {
				query := Page(args)
%s
				result, err := call.Get(ctx, %q, query)
				if err != nil {
					return nil, err
				}
				if !result.OK() {
					return nil, fmt.Errorf("%%s", result.Message())
				}
				var rows []map[string]any
				if err := result.Decode(&rows); err != nil {
					return nil, err
				}
				return map[string]any{"%s": rows, "count": len(rows)}, nil
			},
		},
`,
		plural, n.PluralPascal, labels,
		n.PluralPascal, plural+".view", base,
		indentProps(props),
		g.mcpFilterAssignments(),
		base,
		plural,
	)
}

func (g *Generator) mcpGetTool(label, single, plural, base string) string {
	n := g.Names()
	return fmt.Sprintf(`		Tool{
			Name:  "get_%s",
			Title: "Get one %s",
			Description: "One %s in full, by its id%s.",
			Group:      %q,
			Permission: %q,
			Routes:     []string{"GET %s", "GET %s/:id"},
			Schema: map[string]any{
				"type": "object",
				"properties": map[string]any{
					"%s": map[string]any{
						"type":        "string",
						"description": "The id%s.",
					},
				},
				"required": []string{"%s"},
			},
			Exec: func(ctx context.Context, call *Call, args map[string]any) (any, error) {
				term, err := String(args, %q)
				if err != nil {
					return nil, err
				}
				id, err := Resolve(ctx, call, %q, %q, term)
				if err != nil {
					return nil, err
				}
				result, err := call.Get(ctx, %q+"/"+id, nil)
				if err != nil {
					return nil, err
				}
				if !result.OK() {
					return nil, fmt.Errorf("%%s", result.Message())
				}
				var row map[string]any
				if err := result.Decode(&row); err != nil {
					return nil, err
				}
				return row, nil
			},
		},
`,
		single, n.Pascal, label, g.mcpLabelHint(),
		n.PluralPascal, plural+".view", base, base,
		single, g.mcpLabelHint(), single,
		single,
		label, base,
		base,
	)
}

func (g *Generator) mcpCreateTool(label, single, plural, base string) string {
	n := g.Names()

	writable := g.writableForMCP()
	var props []string
	var required []string
	for _, f := range writable {
		props = append(props, fmt.Sprintf(`%q: %s`, f.Name, g.mcpFieldSchema(f, true)))
		if f.Required {
			required = append(required, strconv.Quote(f.Name))
		}
	}

	requiredLine := ""
	if len(required) > 0 {
		requiredLine = fmt.Sprintf("\n\t\t\t\t\"required\": []string{%s},", strings.Join(required, ", "))
	}

	return fmt.Sprintf(`		Tool{
			Name:  "create_%s",
			Title: "Create a %s",
			Description: "Adds a %s. Validation is the API's, so a refusal names " +
				"the fields and what is wrong with each.",
			Group:      %q,
			Permission: %q,
			Write:      true,
			Routes:     []string{"POST %s"%s},
			Schema: map[string]any{
				"type": "object",
				"properties": map[string]any{
%s
				},%s
			},
			Exec: func(ctx context.Context, call *Call, args map[string]any) (any, error) {
				body, err := %sBody(ctx, call, args, true)
				if err != nil {
					return nil, err
				}
				result, err := call.Post(ctx, %q, body)
				if err != nil {
					return nil, err
				}
				if !result.OK() {
					return nil, fmt.Errorf("%%s", result.Message())
				}
				var row map[string]any
				if err := result.Decode(&row); err != nil {
					return nil, err
				}
				return row, nil
			},
		},
`,
		single, n.Pascal, label,
		n.PluralPascal, plural+".create", base, g.mcpRelationRoutes(),
		indentProps(props), requiredLine,
		n.Camel,
		base,
	)
}

func (g *Generator) mcpUpdateTool(label, single, plural, base string) string {
	n := g.Names()

	var props []string
	props = append(props, fmt.Sprintf(`"%s": map[string]any{"type": "string", "description": "The id%s of the %s to change."}`,
		single, g.mcpLabelHint(), label))
	for _, f := range g.writableForMCP() {
		props = append(props, fmt.Sprintf(`%q: %s`, f.Name, g.mcpFieldSchema(f, false)))
	}

	return fmt.Sprintf(`		Tool{
			Name:  "update_%s",
			Title: "Update a %s",
			Description: "Changes the fields you pass and leaves the rest alone. " +
				"Every field is optional here, unlike on create.",
			Group:      %q,
			Permission: %q,
			Write:      true,
			Routes:     []string{"GET %s", "PATCH %s/:id"%s},
			Schema: map[string]any{
				"type": "object",
				"properties": map[string]any{
%s
				},
				"required": []string{%q},
			},
			Exec: func(ctx context.Context, call *Call, args map[string]any) (any, error) {
				term, err := String(args, %q)
				if err != nil {
					return nil, err
				}
				id, err := Resolve(ctx, call, %q, %q, term)
				if err != nil {
					return nil, err
				}
				body, err := %sBody(ctx, call, args, false)
				if err != nil {
					return nil, err
				}
				if len(body) == 0 {
					return nil, fmt.Errorf("nothing to change: pass at least one field")
				}
				result, err := call.Patch(ctx, %q+"/"+id, body)
				if err != nil {
					return nil, err
				}
				if !result.OK() {
					return nil, fmt.Errorf("%%s", result.Message())
				}
				var row map[string]any
				if err := result.Decode(&row); err != nil {
					return nil, err
				}
				return row, nil
			},
		},
`,
		single, n.Pascal,
		n.PluralPascal, plural+".edit", base, base, g.mcpRelationRoutes(),
		indentProps(props),
		single,
		single,
		label, base,
		n.Camel,
		base,
	)
}

