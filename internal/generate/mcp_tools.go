// mcpBodyBuilder emits the one function create and update share.
//
// Shared because the two differ in exactly one way, which is whether a missing
// required field is an error, and writing it twice is how they drift: a field
// added to create and forgotten on update is a field an agent can set once and
// never correct.
func (g *Generator) mcpBodyBuilder() string {
	n := g.Names()

	var lines []string
	for _, f := range g.writableForMCP() {
		lines = append(lines, g.mcpBodyLine(f))
	}

	return fmt.Sprintf(`
// %sBody turns a model's arguments into the request body.
//
// One function for create and update, which differ only in whether a missing
// required field is an error. Two copies drift: a field added to create and
// forgotten on update is one an agent can set once and never correct.
func %sBody(ctx context.Context, call *Call, args map[string]any, creating bool) (map[string]any, error) {
	body := map[string]any{}
	_ = ctx
	_ = call
%s
	return body, nil
}
`, n.Camel, n.Camel, strings.Join(lines, "\n"))
}

// mcpBodyLine is how one field is read.
func (g *Generator) mcpBodyLine(f Field) string {
	name := f.Name
	req := f.Required

	switch f.Type {
	case "int", "uint", "rating", "percent":
		return fmt.Sprintf(`	if value, err := Int(args, %q); err == nil {
		body[%q] = value
	}%s`, name, name, requiredErrElse(req))

	case "float", "money":
		return fmt.Sprintf(`	if value, err := Float(args, %q); err == nil {
		// Ordinary units in, as a model will always send them: the API
		// converts to minor units on the way through.
		body[%q] = value
	}%s`, name, name, requiredErrElse(req))

	case "bool", "toggle", "check":
		return fmt.Sprintf(`	if _, present := args[%q]; present {
		body[%q] = Bool(args, %q, false)
	}`, name, name, name)

	case "string_array", "many_to_many":
		return fmt.Sprintf(`	if value := Strings(args, %q); len(value) > 0 {
		body[%q] = value
	}`, name, name)

	case "belongs_to", "one_to_one":
		related := f.RelatedModel
		path := "/api/v1/" + Pluralize(strings.ReplaceAll(toSnakeCase(related), "_", "-"))
		// The column is client_id, not client: the model names the foreign key
		// with the _id suffix and the create schema requires it under that
		// name. The argument stays bare, because "client" is what a person
		// says and the whole point of the lookup is to accept a name there.
		return fmt.Sprintf(`	if term := OptionalString(args, %q); term != "" {
		// A name as readily as an id, because that is what the person said.
		related, err := Resolve(ctx, call, %q, %q, term)
		if err != nil {
			return nil, err
		}
		body[%q] = related
	}%s`, name, strings.ToLower(humanizeLabel(related)), path, f.relationBodyKey(),
			requiredElse(req, name))

	default:
		return fmt.Sprintf(`	if value, err := String(args, %q); err == nil {
		body[%q] = value
	}%s`, name, name, requiredErrElse(req))
	}
}

// mcpFieldSchema is one field's JSON Schema.
func (g *Generator) mcpFieldSchema(f Field, creating bool) string {
	switch f.Type {
	case "int", "uint":
		return `map[string]any{"type": "integer"}`
	case "rating":
		return `map[string]any{"type": "integer", "minimum": 1, "maximum": 5}`
	case "percent":
		return `map[string]any{"type": "number", "minimum": 0, "maximum": 100}`
	case "float":
		return `map[string]any{"type": "number"}`
	case "money":
		return `map[string]any{"type": "number", "description": "In ordinary units, not minor units: 40 means forty."}`
	case "bool", "toggle", "check":
		return `map[string]any{"type": "boolean"}`
	case "date":
		return `map[string]any{"type": "string", "format": "date", "description": "YYYY-MM-DD."}`
	case "datetime":
		return `map[string]any{"type": "string", "format": "date-time", "description": "RFC 3339."}`
	case "time":
		return `map[string]any{"type": "string", "description": "HH:MM, 24 hour."}`
	case "email":
		return `map[string]any{"type": "string", "format": "email"}`
	case "url":
		return `map[string]any{"type": "string", "format": "uri"}`
	case "select", "radio":
		if values := f.OptionValues(); len(values) > 0 {
			quoted := make([]string, 0, len(values))
			for _, v := range values {
				quoted = append(quoted, strconv.Quote(v))
			}
			return fmt.Sprintf(`map[string]any{"type": "string", "enum": []string{%s}}`,
				strings.Join(quoted, ", "))
		}
		return `map[string]any{"type": "string"}`
	case "string_array", "many_to_many":
		return `map[string]any{"type": "array", "items": map[string]any{"type": "string"}}`
	case "belongs_to", "one_to_one":
		return fmt.Sprintf(`map[string]any{"type": "string", "description": "The %s's id, or its name."}`,
			strings.ToLower(humanizeLabel(f.RelatedModel)))
	case "json", "vector":
		return `map[string]any{"type": "string", "description": "JSON, as text."}`
	default:
		return `map[string]any{"type": "string"}`
	}
}

// writableForMCP is the fields an agent may set.
//
// The exclusions are the point, and each is a field that must never reach a
// model or a request body:
//
//   - Encrypted and Sensitive: a recovery phrase or a shared secret. Sensitive
//     is never read back at all, so offering it to an agent is offering a
//     write-only field it cannot verify.
//   - ServerSet: the server fills it, so a value an agent sends is overwritten
//     by the next hook. Asking for it is asking for a number that does nothing.
//   - file and files: an upload is a multipart request this transport does not
//     make, and a model cannot produce the bytes.
//   - slug: derived from its source field, so setting it directly puts the two
//     out of step.
func (g *Generator) writableForMCP() []Field {
	var out []Field
	for _, f := range g.Definition.Fields {
		if f.Encrypted || f.Sensitive || f.ServerSet {
			continue
		}
		switch f.Type {
		case "file", "files", "slug", "password":
			continue
		}
		if f.Name == "id" || isAutoField(f.Name) {
			continue
		}
		out = append(out, f)
	}
	return out
}

// filterableForMCP is the fields worth offering as a list filter.
//
// A subset on purpose. Every field as a filter makes a schema a model has to
// read before every call, and the ones that pay for themselves are the ones
// somebody filters by in the UI: a status, a flag, a relation.
func (g *Generator) filterableForMCP() []Field {
	var out []Field
	for _, f := range g.writableForMCP() {
		switch f.Type {
		case "select", "radio", "bool", "toggle", "check", "belongs_to":
			out = append(out, f)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// mcpFilterAssignments reads the filters into the query.
func (g *Generator) mcpFilterAssignments() string {
	fields := g.filterableForMCP()
	if len(fields) == 0 {
		return ""
	}
	var b strings.Builder
	for _, f := range fields {
		switch f.Type {
		case "bool", "toggle", "check":
			fmt.Fprintf(&b, `				if _, present := args[%q]; present {
					query.Set(%q, boolText(Bool(args, %q, false)))
				}
`, f.Name, f.Name, f.Name)
		default:
			fmt.Fprintf(&b, `				if value := OptionalString(args, %q); value != "" {
					query.Set(%q, value)
				}
`, f.Name, f.Name)
		}
	}
	return strings.TrimRight(b.String(), "\n")
}

// mcpRelationRoutes is the extra routes a tool needs to resolve a name.
//
// A belongs_to argument accepts a name, and resolving it is a GET on the
// related resource. That read has to be in Routes or the connection's key
// refuses it at runtime: the allowlist is the union of its tools' routes, and
// a route the tool forgot to declare is one the app will not let it call.
func (g *Generator) mcpRelationRoutes() string {
	seen := map[string]bool{}
	var routes []string
	for _, f := range g.writableForMCP() {
		if f.Type != "belongs_to" && f.Type != "one_to_one" {
			continue
		}
		route := "GET /api/v1/" + Pluralize(strings.ReplaceAll(toSnakeCase(f.RelatedModel), "_", "-"))
		if seen[route] {
			continue
		}
		seen[route] = true
		routes = append(routes, route)
	}
	sort.Strings(routes)

	var b strings.Builder
	for _, route := range routes {
		fmt.Fprintf(&b, ", %q", route)
	}
	return b.String()
}

// mcpLabelHint says whether a name works in place of an id, which depends on
// the resource having something to search.
func (g *Generator) mcpLabelHint() string {
	for _, f := range g.Definition.Fields {
		if f.Type == "string" && !f.Encrypted && !f.Sensitive {
			return ", or its " + f.Name
		}
	}
	return ""
}

// indentProps lays the schema properties out one per line.
func indentProps(props []string) string {
	var b strings.Builder
	for i, prop := range props {
		b.WriteString("\t\t\t\t\t" + prop + ",")
		if i < len(props)-1 {
			b.WriteString("\n")
		}
	}
	return b.String()
}

// relationBodyKey is the column a belongs_to writes to.
//
// The model names the foreign key with an _id suffix and the create schema
// requires it under that name, so a body keyed on the bare field name is
// refused: 422, "client_id is required", for a request that named the client
// perfectly well. The argument a model sends stays bare, because "client" is
// what a person says.
func (f Field) relationBodyKey() string {
	if strings.HasSuffix(f.Name, "_id") {
		return f.Name
	}
	return f.Name + "_id"
}

// requiredElse is the else branch for a required relation, and nothing for an
// optional one.
//
// Emitted rather than always written, because "else if creating && false" is
// dead code and "else if creating && true" is noise: generated code is read
// by people, and a condition that is a constant tells the reader the generator
// could not be bothered.
func requiredElse(required bool, name string) string {
	if !required {
		return ""
	}
	return fmt.Sprintf(` else if creating {
		return nil, fmt.Errorf("%s is required")
	}`, name)
}

// requiredErrElse is the same for a field read by a typed helper, which
// already has the error to return.
func requiredErrElse(required bool) string {
	if !required {
		return ""
	}
	return ` else if creating {
		return nil, err
	}`
}
