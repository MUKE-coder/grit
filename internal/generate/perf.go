package generate

import (
	"fmt"
	"strings"

	"github.com/MUKE-coder/grit/v3/internal/scaffold"
)

// PerfOptions configures a generated k6 load test.
type PerfOptions struct {
	// Resource, if set, adds a scenario that lists that resource's collection
	// endpoint (e.g. "Blog" → GET /api/blogs). Empty = health + auth only.
	Resource string
	// VUs is the peak number of virtual users (concurrent clients).
	VUs int
	// Duration is how long to hold at peak (k6 stage duration, e.g. "30s", "2m").
	Duration string
	// BaseURL is the default target; overridable at run time via BASE_URL.
	BaseURL string
}

func (o *PerfOptions) applyDefaults() {
	if o.VUs <= 0 {
		o.VUs = 20
	}
	if strings.TrimSpace(o.Duration) == "" {
		o.Duration = "30s"
	}
	if strings.TrimSpace(o.BaseURL) == "" {
		o.BaseURL = projectBaseURL()
	}
}

// projectBaseURL is the project's own APP_URL, falling back to the scaffold
// default when there is no .env to read (a bare BuildPerfScript in a test).
//
// It used to be the hardcoded default below, which meant a project on any
// other port got a load test that could not connect to it. APP_URL is the
// value to read rather than APP_PORT, because a project behind a proxy has a
// URL that is not "localhost:" plus its port.
func projectBaseURL() string {
	if url := strings.TrimSpace(scaffold.ReadDotEnv(".env")["APP_URL"]); url != "" {
		return strings.TrimRight(url, "/")
	}
	return "http://localhost:8080"
}

// GeneratePerf writes a k6 load test (perf/load.js) and a runbook (perf/README.md)
// into the current project. The script follows Grit's API conventions: it
// registers and logs in a user in setup() to obtain a bearer token, then every
// virtual user hammers the health check, the authenticated profile read, and —
// if a resource is named — that resource's list endpoint. Thresholds fail the
// run if the error rate or p95 latency crosses a line, so it doubles as a
// regression gate in CI, not just an ad-hoc benchmark.
func GeneratePerf(opts PerfOptions) error {
	opts.applyDefaults()

	if err := writeFileWithDirs("perf/load.js", perfScript(opts)); err != nil {
		return fmt.Errorf("writing perf/load.js: %w", err)
	}
	if err := writeFileWithDirs("perf/pulse.js", perfPulseBridge()); err != nil {
		return fmt.Errorf("writing perf/pulse.js: %w", err)
	}
	if err := writeFileWithDirs("perf/README.md", perfReadme(opts)); err != nil {
		return fmt.Errorf("writing perf/README.md: %w", err)
	}
	return nil
}

// perfScript renders the k6 script. It is exported-for-test via BuildPerfScript
// so the generator's output can be asserted without touching the filesystem.
func perfScript(opts PerfOptions) string {
	opts.applyDefaults()

	resourceScenario := ""
	if opts.Resource != "" {
		plural := Pluralize(strings.ToLower(opts.Resource))
		lower := strings.ToLower(opts.Resource)
		// Generated resource routes sit behind RequireRole("ADMIN", "perm:..."),
		// so the throwaway USER this script registers is refused. Without the
		// guard every run reported a third of its checks failing and the
		// threshold gate went red on a healthy API, which is worse than not
		// testing the route at all.
		resourceScenario = fmt.Sprintf(`
  // 3. %s collection — the CRUD read path under load.
  //
  // Only when PERF_EMAIL/PERF_PASSWORD named an account that may read it.
  // Generated resource routes require ADMIN or the matching permission, so
  // the throwaway user registered in setup() would get 403 on every call and
  // fail the error-rate threshold on a perfectly healthy API.
  if (data.staff) {
    const list = http.get(`+"`${BASE}/api/%s`"+`, authParams);
    check(list, { '%s list is 200': (r) => r.status === 200 });
  }
`, opts.Resource, plural, lower)
	}

	return fmt.Sprintf(`// k6 load test for this Grit API. Generated by `+"`grit generate perf`"+`.
//
// Run it:   k6 run perf/load.js
// Override: BASE_URL=https://staging.example.com k6 run perf/load.js
//
// The thresholds below fail the run (non-zero exit) if the error rate or p95
// latency regresses, so this works as a CI gate as well as an ad-hoc benchmark.
//
// The run also registers itself with Pulse, which is what turns "p95 was
// 310ms" into "p95 was 310ms and here is the flame graph of those 310ms".
// See perf/pulse.js; it is a no-op when PULSE_PASSWORD is not set.
import http from 'k6/http';
import { check, sleep } from 'k6';
import { pulseBase, pulseLogin, pulseStartRun, pulseEndRun } from './pulse.js';

const BASE = __ENV.BASE_URL || '%s';

export const options = {
  // Ramp to %d virtual users, hold for %s, then ramp down.
  stages: [
    { duration: '10s', target: %d },
    { duration: '%s', target: %d },
    { duration: '10s', target: 0 },
  ],
  thresholds: {
    http_req_failed: ['rate<0.01'],   // fewer than 1%% of requests may fail
    http_req_duration: ['p(95)<500'], // 95%% of requests must finish under 500ms
  },
};

// setup() runs once before the load. It registers a throwaway user and logs in,
// returning a bearer token every virtual user shares — Grit accepts
// "Authorization: Bearer <token>", which sidesteps cookie jars and CSRF.
export function setup() {
  // PERF_EMAIL/PERF_PASSWORD log in as an existing account, which is how you
  // load-test routes that need a role: a resource endpoint generated by
  // "grit generate resource" requires ADMIN or its own permission. Without
  // them a throwaway USER is registered, and anything role-guarded is skipped
  // rather than counted as a failure.
  const staff = Boolean(__ENV.PERF_EMAIL && __ENV.PERF_PASSWORD);
  const email = __ENV.PERF_EMAIL || `+"`perf+${Date.now()}@loadtest.local`"+`;
  const password = __ENV.PERF_PASSWORD || 'Password123!';
  const json = { headers: { 'Content-Type': 'application/json' } };

  if (!staff) {
    http.post(`+"`${BASE}/api/auth/register`"+`, JSON.stringify({
      first_name: 'Load', last_name: 'Test', email, password,
    }), json);
  }

  const res = http.post(`+"`${BASE}/api/auth/login`"+`, JSON.stringify({ email, password }), json);
  const token = res.json('data.tokens.access_token');
  if (!token) {
    throw new Error('setup: could not obtain an access token (login returned ' + res.status + ')');
  }

  // Tell Pulse the run is starting. It takes a CPU profile over the window
  // when profiling is on, and compares traffic before, during and after.
  const pulse = pulseBase(BASE);
  const pulseToken = pulseLogin(pulse);
  const run = pulseStartRun(pulse, pulseToken, {
    name: 'grit generate perf: %d VUs for %s',
    type: 'k6.average-load',
    metadata: { vus_peak: %d, hold: '%s', base_url: BASE },
  });

  return { token, staff, pulse, pulseToken, run };
}

// teardown() runs once after the load, and closes the Pulse run so the profile
// is stopped and kept. k6 runs it even when a threshold failed, which is the
// run you most want the profile for.
export function teardown(data) {
  pulseEndRun(data.pulse, data.pulseToken, data.run, { completed: true });
}

export default function (data) {
  const authParams = { headers: { Authorization: `+"`Bearer ${data.token}`"+` } };

  // 1. Health check (unauthenticated) — the cheapest liveness path.
  const health = http.get(`+"`${BASE}/api/health`"+`);
  check(health, { 'health is 200': (r) => r.status === 200 });

  // 2. Authenticated profile read — exercises the auth middleware per request.
  const profile = http.get(`+"`${BASE}/api/profile`"+`, authParams);
  check(profile, { 'profile is 200': (r) => r.status === 200 });
%s
  sleep(1);
}
`, opts.BaseURL, opts.VUs, opts.Duration, opts.VUs, opts.Duration, opts.VUs,
		opts.VUs, opts.Duration, opts.VUs, opts.Duration, resourceScenario)
}

// BuildPerfScript exposes the rendered script for tests.
func BuildPerfScript(opts PerfOptions) string { return perfScript(opts) }

func perfReadme(opts PerfOptions) string {
	opts.applyDefaults()

	resourceLine := ""
	if opts.Resource != "" {
		resourceLine = fmt.Sprintf("- `GET /api/%s`: %s collection under load\n",
			Pluralize(strings.ToLower(opts.Resource)), opts.Resource)
	}

	return fmt.Sprintf("# Load testing\n\n"+
		"A [k6](https://k6.io) load test lives in `perf/load.js`, generated by "+
		"`grit generate perf`.\n\n"+
		"## Run it\n\n"+
		"```bash\n"+
		"# install k6: https://grafana.com/docs/k6/latest/set-up/install-k6/\n"+
		"set -a; source .env; set +a   # so the run is recorded in Pulse, see below\n"+
		"k6 run perf/load.js\n\n"+
		"# against another environment\n"+
		"BASE_URL=https://staging.example.com k6 run perf/load.js\n"+
		"```\n\n"+
		"## It records itself in Pulse\n\n"+
		"k6 tells you p95 went from 40ms to 310ms. It cannot tell you which "+
		"function, and neither can an external APM at the resolution that matters. "+
		"Pulse can, because it is inside the API process.\n\n"+
		"`perf/pulse.js` registers the run before the load starts and closes it "+
		"after, which gets you three things k6 has no way to measure:\n\n"+
		"- **Before / during / after traffic, per route**, from the API's own "+
		"per-minute rollups rather than from k6's view of its own requests\n"+
		"- **Queries per request and N+1 findings** in each window. An N+1 that is "+
		"invisible at one request a second is exactly what falls over at 500 VUs\n"+
		"- **A CPU profile captured over the run**, so the slow p95 arrives with the "+
		"flame graph of what was burning during it\n\n"+
		"It needs the Pulse dashboard password, which is already in `.env`:\n\n"+
		"```bash\n"+
		"set -a; source .env; set +a          # PULSE_USERNAME / PULSE_PASSWORD\n"+
		"k6 run perf/load.js\n\n"+
		"# or pass it directly\n"+
		"k6 run -e PULSE_PASSWORD=... perf/load.js\n"+
		"```\n\n"+
		"The profile needs profiling switched on, which is off by default: set "+
		"`PULSE_PROFILING=true` in `.env` and `PULSE_PROFILE_ENABLED=true` in the "+
		"environment the server runs in. Without it the run is still recorded and "+
		"compared, just without a profile, and the script says which you got.\n\n"+
		"When the run ends, k6 prints the links:\n\n"+
		"```\n"+
		"  Pulse recorded this run:\n"+
		"    Comparison   http://localhost:8080/pulse/ui/test-runs\n"+
		"    Before/after http://localhost:8080/pulse/api/test-runs/<id>/compare\n"+
		"    Flame graph  http://localhost:8080/pulse/api/test-runs/<id>/profile?format=svg\n"+
		"```\n\n"+
		"None of this can fail your load test. With `PULSE_PASSWORD` unset, or "+
		"Pulse disabled, or the dashboard unreachable, every call is a no-op and "+
		"the test runs exactly as it would have.\n\n"+
		"## What it hits\n\n"+
		"Each virtual user, per iteration:\n\n"+
		"- `GET /api/health` — liveness\n"+
		"- `GET /api/profile` — an authenticated read (a bearer token is minted once in `setup()`)\n"+
		resourceLine+
		"\n## Load profile\n\n"+
		"Ramps to **%d virtual users**, holds for **%s**, then ramps down. Tune the "+
		"stages in `perf/load.js`.\n\n"+
		"## Pass/fail\n\n"+
		"The run exits non-zero if either threshold is breached, so it can gate a "+
		"deploy:\n\n"+
		"- `http_req_failed` — error rate must stay **under 1%%**\n"+
		"- `http_req_duration` — **p95 under 500ms**\n",
		opts.VUs, opts.Duration)
}

// BuildPerfReadme exposes the rendered runbook for tests.
func BuildPerfReadme(opts PerfOptions) string { return perfReadme(opts) }
