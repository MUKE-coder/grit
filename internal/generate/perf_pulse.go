package generate

// The Pulse half of `grit generate perf`.
//
// A load test tells you the system got slow at 500 virtual users. It cannot
// tell you which function, and neither can an external APM at the resolution
// that matters. Pulse can, because it runs inside the process, and from
// v1.5.0 it captures a CPU profile over the window of a registered run.
//
// None of that happens on its own. Pulse has had POST /pulse/api/test-runs
// since v1.0 and nothing in a generated project ever called it, so the Test
// Runs page stayed empty, the before/during/after comparison never ran, and
// the best feature in the area was gated behind a curl nobody knew to write.
// This file is the glue.
//
// Two things make it cheaper here than in a generic k6 setup. Pulse is mounted
// on the same origin as the API, so there is no second URL to configure. And
// the dashboard password is already in the project's .env, so there is no new
// secret either.

// perfPulseBridge renders perf/pulse.js: the login, start and end calls, each
// of which gives up quietly rather than failing the run.
func perfPulseBridge() string {
	return "// Pulse bridge for this project's load test. Generated by `grit generate perf`.\n" +
		"//\n" +
		"// Registering a run with Pulse buys three things that k6 cannot report on\n" +
		"// its own, because they are measured from inside the API process:\n" +
		"//\n" +
		"//   1. Before / during / after traffic, per route, from exact per-minute\n" +
		"//      rollups rather than from k6's own view of its own requests.\n" +
		"//   2. Queries per request and N+1 findings in each window. An N+1 that is\n" +
		"//      invisible at one request a second is exactly what falls over at 500\n" +
		"//      virtual users.\n" +
		"//   3. A CPU profile captured over the run, so \"p95 went 40ms to 310ms\"\n" +
		"//      comes with the flame graph of those 310ms.\n" +
		"//\n" +
		"// Everything here is best-effort. With PULSE_PASSWORD unset, or Pulse\n" +
		"// disabled, or the dashboard unreachable, every function below returns null\n" +
		"// and the load test runs exactly as it would have otherwise. A load test\n" +
		"// must not fail because its observability sidecar had a bad day.\n" +
		"import http from 'k6/http';\n" +
		"\n" +
		"// Pulse is mounted on the API's own origin in a Grit project, so PULSE_URL\n" +
		"// only needs setting when you point the test at one host and the dashboard\n" +
		"// at another.\n" +
		"export function pulseBase(apiBase) {\n" +
		"  return __ENV.PULSE_URL || apiBase;\n" +
		"}\n" +
		"\n" +
		"// Its own cookie jar, and this is load-bearing rather than tidiness.\n" +
		"//\n" +
		"// setup() logs into the API first, which sets a session cookie. k6 keeps one\n" +
		"// jar per VU, so without this every Pulse request would carry that cookie,\n" +
		"// and the API's CSRF middleware answers a cookie-bearing POST that has no\n" +
		"// X-CSRF-Token with 403 CSRF_INVALID. The run then silently goes unrecorded.\n" +
		"// Pulse authenticates with a bearer token and wants no cookies at all, so it\n" +
		"// gets an empty jar of its own.\n" +
		"const jar = new http.CookieJar();\n" +
		"\n" +
		"function pulseParams(token) {\n" +
		"  const headers = { 'Content-Type': 'application/json' };\n" +
		"  if (token) headers.Authorization = `Bearer ${token}`;\n" +
		"  return { headers, jar, tags: { pulse: 'true' } };\n" +
		"}\n" +
		"\n" +
		"// pulseLogin returns a dashboard token, or null when Pulse is not configured\n" +
		"// or not answering. `source .env` before k6 and the credentials are already\n" +
		"// in the environment: k6 exposes every environment variable on __ENV.\n" +
		"export function pulseLogin(base) {\n" +
		"  const password = __ENV.PULSE_PASSWORD;\n" +
		"  if (!password) {\n" +
		"    console.warn('pulse: PULSE_PASSWORD is not set, so this run will not be recorded. ' +\n" +
		"      'Run `set -a; source .env; set +a` first, or pass -e PULSE_PASSWORD=...');\n" +
		"    return null;\n" +
		"  }\n" +
		"  const username = __ENV.PULSE_USERNAME || 'admin';\n" +
		"  const res = http.post(`${base}/pulse/api/auth/login`,\n" +
		"    JSON.stringify({ username, password }), pulseParams());\n" +
		"  if (res.status !== 200) {\n" +
		"    console.warn(`pulse: login failed (${res.status}), so this run will not be recorded`);\n" +
		"    return null;\n" +
		"  }\n" +
		"  try {\n" +
		"    return JSON.parse(res.body).token;\n" +
		"  } catch (e) {\n" +
		"    console.warn(`pulse: login response was not the expected shape: ${e}`);\n" +
		"    return null;\n" +
		"  }\n" +
		"}\n" +
		"\n" +
		"// pulseStartRun registers the run as in flight. Pulse starts a CPU profile\n" +
		"// here when profiling is on, and the response says whether it did.\n" +
		"export function pulseStartRun(base, token, opts) {\n" +
		"  if (!token) return null;\n" +
		"  const body = {\n" +
		"    name: opts.name,\n" +
		"    type: opts.type || 'k6.custom',\n" +
		"    started_at: new Date().toISOString(),\n" +
		"    metadata: opts.metadata || {},\n" +
		"  };\n" +
		"  const res = http.post(`${base}/pulse/api/test-runs`, JSON.stringify(body), pulseParams(token));\n" +
		"  if (res.status !== 201) {\n" +
		"    console.warn(`pulse: could not register the run (${res.status}): ${res.body}`);\n" +
		"    return null;\n" +
		"  }\n" +
		"  try {\n" +
		"    const run = JSON.parse(res.body);\n" +
		"    console.log(`pulse: recording run ${run.id}` +\n" +
		"      (run.profiling ? ' with a CPU profile' : ' (profiling is off, so no profile)'));\n" +
		"    return run;\n" +
		"  } catch (e) {\n" +
		"    console.warn(`pulse: run response was not the expected shape: ${e}`);\n" +
		"    return null;\n" +
		"  }\n" +
		"}\n" +
		"\n" +
		"// pulseEndRun closes the run, which stops the profile, and prints where to\n" +
		"// read the result. The links are the point: a run nobody opens is a row in a\n" +
		"// table.\n" +
		"export function pulseEndRun(base, token, run, finalMetadata) {\n" +
		"  if (!token || !run || !run.id) return;\n" +
		"  const body = {\n" +
		"    id: run.id,\n" +
		"    name: run.name,\n" +
		"    type: run.type,\n" +
		"    started_at: run.started_at,\n" +
		"    ended_at: new Date().toISOString(),\n" +
		"    metadata: Object.assign({}, run.metadata || {}, finalMetadata || {}),\n" +
		"  };\n" +
		"  const res = http.post(`${base}/pulse/api/test-runs`, JSON.stringify(body), pulseParams(token));\n" +
		"  if (res.status !== 201) {\n" +
		"    console.warn(`pulse: could not close the run (${res.status}): ${res.body}`);\n" +
		"    return;\n" +
		"  }\n" +
		"  console.log('');\n" +
		"  console.log('  Pulse recorded this run:');\n" +
		"  console.log(`    Comparison  ${base}/pulse/ui/test-runs`);\n" +
		"  console.log(`    Before/after ${base}/pulse/api/test-runs/${run.id}/compare`);\n" +
		"  console.log(`    Flame graph ${base}/pulse/api/test-runs/${run.id}/profile?format=svg`);\n" +
		"  console.log('');\n" +
		"}\n"
}

// BuildPerfPulseBridge exposes the rendered bridge for tests.
func BuildPerfPulseBridge() string { return perfPulseBridge() }
