"""Build the Go Full course from the book.

The course is NOT a second copy of the book. It is the book, rendered as
lessons, generated by this script. That is the whole design: the user asked
for a course covering everything in the book with all its tests and
assignments, and consistent with it. Two hand-written copies of 61 chapters
would be inconsistent within a month, so there is one source and a generator.

What it writes, all of it derived:

  docs/content/lessons/go-full/<part>/<chapter>.tsx   one per book chapter
  docs/config/go-full-course.generated.ts             the course structure
  docs/lib/lesson-content.go-full.generated.ts        the import registry

Nothing here is hand-edited. To change a lesson, change the chapter.

Run: python scripts/go-course-build.py
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
CHAPTERS = os.path.join(ROOT, 'BOOK', 'chapters')
LESSONS = os.path.join(ROOT, 'docs', 'content', 'lessons', 'go-full')
CONFIG = os.path.join(ROOT, 'docs', 'config', 'go-full-course.generated.ts')
REGISTRY = os.path.join(ROOT, 'docs', 'lib', 'lesson-content.go-full.generated.ts')

COURSE_SLUG = 'go-full'

# The book's own six parts, from the comments in book.typ. Chapter 0 stands
# alone because it is setup rather than Go.
PARTS = [
    ('start', 'Before you start', 'The repository and the leaderboard, before any Go.', (0, 0)),
    ('language', 'The language', 'Go taught against the JavaScript you already know.', (1, 9)),
    ('what-separates-go', 'What separates Go', 'Interfaces, errors, concurrency, generics, testing.', (10, 19)),
    ('standard-library', 'The standard library', 'Real programs with nothing but what ships with Go.', (20, 25)),
    ('grit', 'Grit', 'The framework, now that you can read what it generates.', (26, 36)),
    ('building', 'Building with Grit', 'A real application, feature by feature.', (37, 47)),
    ('first-principles', 'From first principles', 'Rebuild the tools you have been using.', (48, 58)),
]

# Reading speed. The book is dense, so this is deliberately not optimistic:
# a page of Go prose with code on it is not a page of a novel.
WORDS_PER_MINUTE = 140


# ── Typst parsing ────────────────────────────────────────────────────────

CALLOUTS = {
    'bridge': ('info', 'If you know JavaScript'),
    'gotcha': ('warning', 'Watch out'),
    'project': ('success', 'Project'),
    'tryit': ('info', 'Your turn'),
    'note': ('info', ''),
}


def read_chapter(path):
    return io.open(path, encoding='utf-8').read()


def match_bracket(text, start):
    """Index just past the ] that closes the [ at start."""
    depth = 0
    i = start
    while i < len(text):
        c = text[i]
        if c == '\\':
            i += 2
            continue
        if c == '[':
            depth += 1
        elif c == ']':
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return len(text)


def match_paren(text, start):
    depth = 0
    i = start
    while i < len(text):
        c = text[i]
        if c == '\\':
            i += 2
            continue
        if c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return len(text)


def parse(text):
    """Typst chapter -> a list of blocks."""
    blocks = []
    i = 0
    buf = []

    def flush():
        if buf:
            para = '\n'.join(buf).strip()
            if para:
                blocks.append(('para', para))
            buf.clear()

    lines = text.splitlines()
    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        if stripped.startswith('#import'):
            i += 1
            continue

        # Fenced code
        if stripped.startswith('```'):
            flush()
            lang = stripped[3:].strip() or 'text'
            i += 1
            code = []
            while i < len(lines) and not lines[i].strip().startswith('```'):
                code.append(lines[i])
                i += 1
            i += 1
            blocks.append(('code', lang, dedent(code)))
            continue

        # Headings
        m = re.match(r'^(=+)\s+(.*)$', stripped)
        if m:
            flush()
            blocks.append(('heading', len(m.group(1)), m.group(2).strip()))
            i += 1
            continue

        # A #func[...] or #func(args)[...] that starts a line
        m = re.match(r'^#(\w+)', stripped)
        if m:
            name = m.group(1)
            rest = '\n'.join(lines[i:])
            offset = rest.index('#' + name)
            after = offset + 1 + len(name)

            args = ''
            if after < len(rest) and rest[after] == '(':
                end = match_paren(rest, after)
                args = rest[after:end]
                after = end

            if after < len(rest) and rest[after] == '[':
                flush()
                end = match_bracket(rest, after)
                body = rest[after + 1:end - 1]
                consumed = rest[:end].count('\n')
                if name == 'assignment':
                    nm = re.search(r'name:\s*"([^"]*)"', args)
                    blocks.append(('assignment', nm.group(1) if nm else '', body))
                elif name in CALLOUTS:
                    tone, title = CALLOUTS[name]
                    t = re.search(r'title:\s*"([^"]*)"', args)
                    blocks.append(('callout', tone, t.group(1) if t else title, body))
                else:
                    blocks.append(('para', body))
                i += consumed + 1
                continue

            # A #table(...) or any other call with no body: keep its cells as
            # a list rather than losing the content.
            if args:
                flush()
                cells = re.findall(r'\[([^\[\]]*)\]', args)
                if cells:
                    blocks.append(('list', cells))
                consumed = args.count('\n')
                i += consumed + 1
                continue

        # Bullets
        if stripped.startswith('- '):
            flush()
            items = []
            while i < len(lines) and lines[i].strip().startswith('- '):
                item = [lines[i].strip()[2:]]
                i += 1
                while (i < len(lines) and lines[i].strip()
                       and not lines[i].strip().startswith('- ')
                       and lines[i].startswith((' ', '\t'))):
                    item.append(lines[i].strip())
                    i += 1
                items.append(' '.join(item))
            blocks.append(('list', items))
            continue

        if not stripped:
            flush()
            i += 1
            continue

        buf.append(stripped)
        i += 1

    flush()
    return blocks


def dedent(lines):
    real = [l for l in lines if l.strip()]
    if not real:
        return ''
    pad = min(len(l) - len(l.lstrip()) for l in real)
    return '\n'.join(l[pad:] if len(l) >= pad else l for l in lines).strip('\n')


# ── TSX emission ─────────────────────────────────────────────────────────

def jsx_text(s):
    """Typst inline markup to JSX, with the characters JSX cannot take raw."""
    s = s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    s = s.replace('{', '&#123;').replace('}', '&#125;')
    # `code` first: its contents must not then be bolded or italicised.
    parts = re.split(r'(`[^`]*`)', s)
    out = []
    for part in parts:
        if part.startswith('`') and part.endswith('`') and len(part) > 1:
            out.append('<code>' + part[1:-1] + '</code>')
            continue
        part = re.sub(r'\*([^*\n]+)\*', r'<strong>\1</strong>', part)
        part = re.sub(r'(?<![\w#])_([^_\n]+)_(?![\w])', r'<em>\1</em>', part)
        part = part.replace("'", '&apos;').replace('"', '&quot;')
        out.append(part)
    return ''.join(out)


def template_literal(code):
    """Go source inside a JS template literal.

    Backticks and ${ both end or interpolate the literal, and Go struct tags
    are full of backticks. Getting this wrong produces a file that builds and
    renders the wrong thing, or does not build at all.
    """
    return code.replace('\\', '\\\\').replace('`', '\\`').replace('${', '\\${')


def emit(blocks, title):
    body = []
    uses = set()

    for b in blocks:
        kind = b[0]
        if kind == 'heading':
            level, text = b[1], b[2]
            if level == 1:
                continue          # the lesson shell prints the title
            tag = 'h2' if level == 2 else 'h3'
            body.append(f'      <{tag}>{jsx_text(text)}</{tag}>')
        elif kind == 'para':
            body.append(f'      <p>{jsx_text(b[1])}</p>')
        elif kind == 'list':
            items = '\n'.join(f'        <li>{jsx_text(x)}</li>' for x in b[1])
            body.append(f'      <ul>\n{items}\n      </ul>')
        elif kind == 'code':
            uses.add('CodeBlock')
            body.append(
                f'      <CodeBlock language="{b[1]}" code={{`{template_literal(b[2])}`}} />')
        elif kind == 'callout':
            uses.add('TipBox')
            tone, ctitle, inner = b[1], b[2], b[3]
            inner_blocks = parse(inner)
            lines = []
            if ctitle:
                lines.append(f'        <p><strong>{jsx_text(ctitle)}</strong></p>')
            for ib in inner_blocks:
                if ib[0] == 'para':
                    lines.append(f'        <p>{jsx_text(ib[1])}</p>')
                elif ib[0] == 'code':
                    uses.add('CodeBlock')
                    lines.append(
                        f'        <CodeBlock language="{ib[1]}" '
                        f'code={{`{template_literal(ib[2])}`}} />')
                elif ib[0] == 'list':
                    its = '\n'.join(f'          <li>{jsx_text(x)}</li>' for x in ib[1])
                    lines.append(f'        <ul>\n{its}\n        </ul>')
            inner_tsx = '\n'.join(lines)
            body.append(
                f'      <TipBox tone="{tone}">\n{inner_tsx}\n      </TipBox>')
        elif kind == 'assignment':
            uses.add('Exercise')
            name, inner = b[1], b[2]
            inner_blocks = parse(inner)
            lines = []
            for ib in inner_blocks:
                if ib[0] == 'para':
                    lines.append(f'            <p>{jsx_text(ib[1])}</p>')
                elif ib[0] == 'code':
                    uses.add('CodeBlock')
                    lines.append(
                        f'            <CodeBlock language="{ib[1]}" '
                        f'code={{`{template_literal(ib[2])}`}} />')
                elif ib[0] == 'list':
                    its = '\n'.join(f'              <li>{jsx_text(x)}</li>' for x in ib[1])
                    lines.append(f'            <ul>\n{its}\n            </ul>')
                elif ib[0] == 'heading':
                    lines.append(f'            <p><strong>{jsx_text(ib[2])}</strong></p>')
            prompt = '\n'.join(lines)
            body.append(
                '      <h2>Assignment</h2>\n'
                f'      <p>Commit your work with the message '
                f'<code>{jsx_text(name)}</code>, exactly as written, so '
                'the leaderboard can score it.</p>\n'
                '      <Exercise\n'
                '        prompt={<>\n'
                f'{prompt}\n'
                '        </>}\n'
                '        solution={<p>Work it through yourself first. The '
                'chapter above has everything you need, and the leaderboard '
                'scores the commit, not the answer.</p>}\n'
                '      />')

    imports = []
    if 'CodeBlock' in uses:
        imports.append("import { CodeBlock } from '@/components/code-block'")
    if 'TipBox' in uses:
        imports.append("import { TipBox } from '@/components/course/tip-box'")
    if 'Exercise' in uses:
        imports.append("import { Exercise } from '@/components/course/exercise'")

    header = (
        '// Generated by scripts/go-course-build.py from BOOK/chapters.\n'
        '// Do not edit: change the chapter and run the script again.\n'
    )
    return (header + '\n'.join(imports) + '\n\n'
            'export default function Lesson() {\n'
            '  return (\n'
            '    <>\n'
            + '\n\n'.join(body) + '\n'
            '    </>\n'
            '  )\n'
            '}\n')


# ── Structure ────────────────────────────────────────────────────────────

def slug_of(filename):
    return re.sub(r'^\d\d-', '', filename[:-4])


def title_of(text, fallback):
    m = re.search(r'^=\s+(.+)$', text, re.M)
    return m.group(1).strip() if m else fallback


def tagline_of(blocks):
    for b in blocks:
        if b[0] == 'para':
            s = re.sub(r'[`*_]', '', b[1]).replace('\n', ' ')
            s = re.sub(r'\s+', ' ', s).strip()
            cut = s.split('. ')[0].strip()
            if len(cut) > 150:
                cut = cut[:147].rsplit(' ', 1)[0]
            return cut.rstrip('.') + '.'
    return 'A chapter from the book.'


def minutes_of(text):
    words = len(re.findall(r'\S+', text))
    return max(5, round(words / WORDS_PER_MINUTE / 5) * 5)


def difficulty_for(number):
    if number <= 9:
        return 'easy'
    if number <= 25:
        return 'medium'
    return 'hard'


def main():
    files = sorted(f for f in os.listdir(CHAPTERS) if re.match(r'^\d\d-.*\.typ$', f))
    by_number = {}
    for f in files:
        by_number[int(f[:2])] = f

    os.makedirs(LESSONS, exist_ok=True)

    chapters_ts = []
    registry = []
    written = 0
    total_minutes = 0

    for part_slug, part_title, part_tagline, (lo, hi) in PARTS:
        part_dir = os.path.join(LESSONS, part_slug)
        os.makedirs(part_dir, exist_ok=True)

        lessons_ts = []
        goals = []
        assignment_name = None

        for n in range(lo, hi + 1):
            if n not in by_number:
                continue
            fname = by_number[n]
            text = read_chapter(os.path.join(CHAPTERS, fname))
            blocks = parse(text)
            slug = slug_of(fname)
            title = title_of(text, slug)
            tagline = tagline_of(blocks)
            mins = minutes_of(text)
            total_minutes += mins

            io.open(os.path.join(part_dir, slug + '.tsx'), 'w',
                    encoding='utf-8', newline='').write(emit(blocks, title))
            written += 1

            registry.append(
                f"  '{COURSE_SLUG}/{part_slug}/{slug}': () => "
                f"import('@/content/lessons/{COURSE_SLUG}/{part_slug}/{slug}'),")

            lessons_ts.append(
                '        {\n'
                f"          slug: '{slug}',\n"
                f"          title: {ts_str(title)},\n"
                f"          tagline: {ts_str(tagline)},\n"
                f'          minutes: {mins},\n'
                f"          difficulty: '{difficulty_for(n)}',\n"
                "          status: 'available',\n"
                '        },')

            for b in blocks:
                if b[0] == 'heading' and b[1] == 2 and len(goals) < 5:
                    goals.append(b[2])
                if b[0] == 'assignment' and assignment_name is None:
                    assignment_name = b[1]

        if not lessons_ts:
            continue

        chapters_ts.append(
            '  {\n'
            f"    slug: '{part_slug}',\n"
            f'    number: {len(chapters_ts) + 1},\n'
            f"    title: {ts_str(part_title)},\n"
            f"    tagline: {ts_str(part_tagline)},\n"
            '    learningGoals: [\n'
            + '\n'.join(f'      {ts_str(g)},' for g in goals) + '\n'
            '    ],\n'
            '    modules: [\n'
            '      {\n'
            f"        title: {ts_str(part_title)},\n"
            '        lessons: [\n'
            + '\n'.join(lessons_ts) + '\n'
            '        ],\n'
            '      },\n'
            '    ],\n'
            + ('    assignment: {\n'
               f"      title: {ts_str('Finish every assignment in ' + part_title)},\n"
               '      brief:\n'
               f"        {ts_str('Each lesson in this part ends with its own assignment, named for the leaderboard. Finish them in order.')},\n"
               '      successCriteria: [\n'
               f"        {ts_str('Every assignment in this part is committed with its exact name.')},\n"
               f"        {ts_str('go build ./... passes in your practice repository.')},\n"
               f"        {ts_str('go test ./... passes where the chapter asked for tests.')},\n"
               '      ],\n'
               '    },\n' if assignment_name else '')
            + "    status: 'available',\n"
            '  },')

    hours = max(1, round(total_minutes / 60))

    config = f'''// Generated by scripts/go-course-build.py from BOOK/chapters.
// Do not edit: change the book and run the script again.
//
// The Go Full course IS the book, rendered as lessons. One source, so the
// two cannot drift: that is the whole reason this file is generated rather
// than written.

import type {{ Course }} from './courses'

export const GO_FULL_COURSE: Course = {{
  slug: '{COURSE_SLUG}',
  name: 'Go, the Full Course',
  shortName: 'Go Full',
  tagline: 'Every chapter of the book, as lessons, with the assignments.',
  description:
    'The whole of "Go for JavaScript Developers" as a course: the language from zero, the standard library, then Grit, then rebuilding the tools you have been using. Written for somebody who knows JavaScript and has never written Go.',
  level: 'absolute-beginner',
  estimatedHours: {hours},
  prerequisites: ['You can write JavaScript', 'Go installed, or 10 minutes to install it'],
  whatYoullBuild:
    'A practice repository with {written} committed assignments, a URL shortener, a task tracker on Grit, and your own HTTP server, key-value store and job queue.',
  whatYoullLearn: [
    'Go syntax, types, structs, slices, maps and pointers from zero',
    'Interfaces, error design, and why Go has no exceptions',
    'Goroutines, channels, sync and context, in that order',
    'Testing, JSON, files and HTTP with nothing but the standard library',
    'Grit: resources, services, handlers, auth and the admin panel',
    'How the tools work, by rebuilding them',
  ],
  whoThisIsFor: [
    'JavaScript and TypeScript developers moving to Go',
    'Anybody who wants the book with a leaderboard attached',
    'Beginners: every concept is introduced before it is used',
  ],
  status: 'available',
  emoji: '\\u{{1F439}}',
  accent: 'from-sky-500/20 to-cyan-500/5',
  chapters: [
{chr(10).join(chapters_ts)}
  ],
}}
'''

    io.open(CONFIG, 'w', encoding='utf-8', newline='').write(config)

    reg = ('// Generated by scripts/go-course-build.py.\n'
           '// Do not edit: change the book and run the script again.\n'
           '//\n'
           '// A bundler cannot resolve import() with a computed path, which is\n'
           '// why lesson-content.ts keeps an explicit map. This is that map for\n'
           '// the Go Full course, generated so it cannot fall behind the book.\n\n'
           'type LessonComponent = React.ComponentType\n\n'
           'export const GO_FULL_LESSONS: Record<string, () => '
           'Promise<{ default: LessonComponent }>> = {\n'
           + '\n'.join(registry) + '\n}\n')
    io.open(REGISTRY, 'w', encoding='utf-8', newline='').write(reg)

    print(f'{written} lessons written to docs/content/lessons/{COURSE_SLUG}/')
    print(f'{len(chapters_ts)} parts, about {hours} hours')
    print(f'config:   {os.path.relpath(CONFIG, ROOT)}')
    print(f'registry: {os.path.relpath(REGISTRY, ROOT)}')
    return 0


def ts_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


if __name__ == '__main__':
    sys.exit(main())
