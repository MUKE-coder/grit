"""A month of the changelog, as a draft somebody can finish.

The changelog is thorough and that is its job: it says why a change was made,
which is what you want at two in the morning. It is 757 entries, and nobody
reads it to find out what happened this month (grit#266).

This writes the draft. It does not write the post: it reads the entries for
one month, groups them, pulls out the breaking ones and the ones that need a
command, and leaves the judgement to a person. Which five or ten of fifty
releases matter is the whole value of a digest, and a machine that guessed
would produce a list, which is the thing there is already too much of.

The parser is the rollup's, imported rather than rewritten. A third reader of
the changelog page would be a third thing to keep in step with its markup.

Run:
    python scripts/changelog-digest.py 2026-11
    python scripts/changelog-digest.py 2026-11 --write

--write puts it in docs/content/blog/, dated today and named for the month
it covers, and refuses to overwrite one that is already there, because the
point of the draft is that somebody edited it.

Run it for a month that has finished. A digest of a month still in progress
is a list that will be wrong by the end of the week.
"""
import argparse
import datetime as dt
import importlib.util
import io
import os
import re
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PAGE = os.path.join(ROOT, 'docs', 'app', 'docs', 'changelog', 'page.tsx')
BLOG = os.path.join(ROOT, 'docs', 'content', 'blog')


def rollup():
    """The rollup script, as a module. Its filename has a hyphen in it."""
    path = os.path.join(HERE, 'changelog-rollup.py')
    spec = importlib.util.spec_from_file_location('changelog_rollup', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# A release whose entry mentions one of these needs a line in the post saying
# what to run. Deliberately a short list of the commands that change a
# project, not every command Grit has.
COMMANDS = [
    ('grit upgrade', 'brings the framework files in an existing project up to date'),
    ('grit migrate', 'creates or alters tables'),
    ('grit sync', 'regenerates the shared types and schemas'),
    ('grit doctor', 'checks the project'),
]


def entries_for(month):
    """Every entry dated in the given YYYY-MM, newest first."""
    mod = rollup()
    src = io.open(PAGE, encoding='utf-8').read()
    entries, broken, _ = mod.read_entries(src)
    if broken:
        print('note: %d entries could not be read (%s)'
              % (len(broken), ', '.join(broken[:5])))

    want = dt.datetime.strptime(month, '%Y-%m').date()
    chosen = [e for e in entries
              if e['date'] and (e['date'].year, e['date'].month) == (want.year, want.month)]
    chosen.sort(key=lambda e: [int(p) for p in e['version'].split('.')], reverse=True)
    return chosen, src


def body_of(src, version):
    """An entry's prose, for scanning. Not for printing: it is still JSX."""
    at = src.find('{/* v%s' % version)
    if at < 0:
        return ''
    nxt = src.find('{/* v', at + 5)
    return src[at:nxt if nxt > 0 else len(src)]


def commands_in(text):
    return [(cmd, why) for cmd, why in COMMANDS if cmd in text]


def draft(month, chosen, src):
    want = dt.datetime.strptime(month, '%Y-%m').date()
    name = want.strftime('%B %Y')
    breaking = [e for e in chosen if e.get('breaking')]

    needed = []
    for e in chosen:
        for cmd, why in commands_in(body_of(src, e['version'])):
            if cmd not in [c for c, _ in needed]:
                needed.append((cmd, why))

    out = []
    out.append('---')
    out.append('title: "What\'s new in Grit: %s"' % name)
    out.append('subtitle: "TODO: one sentence saying what the month was '
               'about. Write this last, from the five items you keep."')
    out.append('series: "What\'s new in Grit"')
    # Today, not the first of the month it covers. A post dated before the
    # posts written before it sorts above them and claims a publication date
    # it did not have.
    out.append('date: %s' % dt.date.today().isoformat())
    out.append('readingTime: "TODO min"')
    out.append('author: "Muke JohnBaptist"')
    out.append('tags: [grit, release-notes, changelog]')
    out.append('canonical: "https://gritframework.dev/blog/whats-new-in-grit-%s"'
               % want.strftime('%B-%Y').lower())
    out.append('---')
    out.append('')
    out.append('<!-- DRAFT, generated by scripts/changelog-digest.py %s.' % month)
    out.append('')
    out.append('     Keep five to ten. Delete the rest of the list below: a')
    out.append('     digest that lists everything is the changelog again, and')
    out.append('     the changelog is better at being the changelog.')
    out.append('')
    out.append('     For each one you keep, write what it means for somebody')
    out.append('     who has a project running. The entry already says what')
    out.append('     changed; this says whether they need to do anything. -->')
    out.append('')
    out.append('%d releases in %s.' % (len(chosen), name))
    out.append('')

    if breaking:
        out.append('## Breaking')
        out.append('')
        for e in breaking:
            out.append('- **v%s** %s' % (e['version'], e['title']))
        out.append('')
    else:
        out.append('Nothing marked breaking.')
        out.append('')

    if needed:
        out.append('## What to run')
        out.append('')
        for cmd, why in needed:
            out.append('- `%s` %s' % (cmd, why))
        out.append('')
        out.append('<!-- Those are the commands the month\'s entries mention. '
                   'Keep the ones a reader actually needs. -->')
        out.append('')

    out.append('## Everything, to choose from')
    out.append('')
    for e in chosen:
        mark = ' **(breaking)**' if e.get('breaking') else ''
        out.append('- **v%s**%s %s' % (e['version'], mark, e['title']))
    out.append('')
    out.append('[The full changelog for %s](https://gritframework.dev/docs/changelog)'
               % name)
    out.append('')
    return '\n'.join(out)


def slug_for(month):
    """<today>-whats-new-in-grit-<month>-<year>.

    The date prefix is the blog's ordering and is stripped from the slug, so
    the URL names the month and the filename says when it was written.
    """
    want = dt.datetime.strptime(month, '%Y-%m').date()
    return '%s-whats-new-in-grit-%s' % (
        dt.date.today().isoformat(), want.strftime('%B-%Y').lower())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('month', help='the month to digest, as YYYY-MM')
    ap.add_argument('--write', action='store_true',
                    help='write the draft into docs/content/blog')
    args = ap.parse_args()

    if not re.match(r'^\d{4}-\d{2}$', args.month):
        sys.exit('month should be YYYY-MM, for example 2026-11')

    chosen, src = entries_for(args.month)
    if not chosen:
        sys.exit('no changelog entries dated in %s' % args.month)

    text = draft(args.month, chosen, src)
    path = os.path.join(BLOG, slug_for(args.month) + '.md')

    if not args.write:
        print(text)
        print('(pass --write to put this in %s)'
              % os.path.relpath(path, ROOT).replace('\\', '/'))
        return 0

    if os.path.exists(path):
        # Overwriting is the one thing this must never do: the draft exists
        # to be edited, and the edit is the part a machine cannot redo.
        sys.exit('%s already exists. Delete it first if you really want a '
                 'fresh draft.' % os.path.relpath(path, ROOT).replace('\\', '/'))
    io.open(path, 'w', encoding='utf-8', newline='\n').write(text)
    print('wrote %s (%d releases)'
          % (os.path.relpath(path, ROOT).replace('\\', '/'), len(chosen)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
