// Generates lib/component-map.ts — a static map of component name to a
// next/dynamic import.
//
// It has to be generated rather than built at runtime because a bundler cannot
// follow `import('../registry/' + name)`. Generating it from the directory
// listing means a component that exists on disk is always renderable, and one
// that was deleted cannot linger as a broken import.
import fs from 'node:fs'
import path from 'node:path'

const root = path.join(import.meta.dirname, '..')
const registryDir = path.join(root, 'registry')
const outFile = path.join(root, 'lib', 'component-map.ts')

const names = fs
  .readdirSync(registryDir)
  .filter((f) => f.endsWith('.tsx'))
  .map((f) => path.basename(f, '.tsx'))
  .sort()

const pascal = (name) =>
  name
    .split(/[-_]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('')

const lines = [
  '// GENERATED by scripts/generate-component-map.mjs — do not edit by hand.',
  "// Run `pnpm gen` after adding or removing a component in registry/.",
  '',
  "import dynamic from 'next/dynamic'",
  "import type { ComponentType } from 'react'",
  '',
  'export const COMPONENT_MAP: Record<string, ComponentType> = {',
  // The default export is unwrapped explicitly: next/dynamic's loader type
  // accepts a component or a { default } module, and a raw module namespace
  // satisfies neither once `strict` is on.
  ...names.map(
    (n) =>
      `  ${JSON.stringify(n)}: dynamic(() => import('@/registry/${n}').then((m) => ({ default: m.default }))),`,
  ),
  '}',
  '',
  'export const COMPONENT_NAMES = Object.keys(COMPONENT_MAP)',
  '',
  `/** ${names.length} components at generation time. */`,
  `export const COMPONENT_COUNT = ${names.length}`,
  '',
]

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, lines.join('\n'))
console.log(`generated component-map.ts with ${names.length} components`)

// Keep registry.meta.json honest: a metadata entry with no source file would
// advertise a component the registry cannot serve.
const metaPath = path.join(root, 'registry.meta.json')
const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'))
const have = new Set(names)
let changed = 0
for (const m of meta) {
  const has = have.has(m.name)
  if (m.hasSource !== has) {
    m.hasSource = has
    changed++
  }
}
const orphans = names.filter((n) => !meta.some((m) => m.name === n))
if (orphans.length) {
  console.warn(`WARNING: ${orphans.length} component(s) on disk with no metadata entry: ${orphans.join(', ')}`)
}
if (changed) {
  fs.writeFileSync(metaPath, JSON.stringify(meta, null, 2))
  console.log(`updated hasSource on ${changed} metadata entr${changed === 1 ? 'y' : 'ies'}`)
}

const unservable = meta.filter((m) => !m.hasSource)
if (unservable.length) {
  console.warn(
    `WARNING: ${unservable.length} metadata entr${unservable.length === 1 ? 'y has' : 'ies have'} no source and will not be served: ${unservable.map((m) => m.name).join(', ')}`,
  )
}
