// Generates lib/block-map.ts — a static map of registry name to a dynamic
// import of the block component.
//
// Generated rather than resolved at runtime because a bundler cannot follow
// import('../registry/' + path). Driven by the filesystem so a block that
// exists is always renderable, and one that was deleted cannot linger as a
// broken import.
import fs from 'node:fs'
import path from 'node:path'

const root = path.join(import.meta.dirname, '..')
const registryDir = path.join(root, 'registry')
const outFile = path.join(root, 'lib', 'block-map.ts')

/** Walks registry/<category>/<subcategory>/<block>.tsx */
function findBlocks() {
  const found = []
  for (const category of fs.readdirSync(registryDir, { withFileTypes: true })) {
    if (!category.isDirectory()) continue
    const catDir = path.join(registryDir, category.name)
    for (const sub of fs.readdirSync(catDir, { withFileTypes: true })) {
      if (!sub.isDirectory()) continue
      const subDir = path.join(catDir, sub.name)
      for (const file of fs.readdirSync(subDir)) {
        if (!file.endsWith('.tsx')) continue
        found.push({
          category: category.name,
          subcategory: sub.name,
          slug: path.basename(file, '.tsx'),
        })
      }
    }
  }
  return found.sort((a, b) =>
    `${a.category}/${a.subcategory}/${a.slug}`.localeCompare(
      `${b.category}/${b.subcategory}/${b.slug}`,
    ),
  )
}

const blocks = findBlocks()

const lines = [
  '// GENERATED by scripts/generate-block-map.mjs — do not edit by hand.',
  '// Run `pnpm gen` after adding or removing a block in registry/.',
  '',
  "import dynamic from 'next/dynamic'",
  "import type { ComponentType } from 'react'",
  '',
  '/** Keyed by the flat registry name: <category>-<subcategory>-<slug>. */',
  'export const BLOCK_MAP: Record<string, ComponentType> = {',
  // The default export is unwrapped explicitly: next/dynamic's loader accepts a
  // component or a { default } module, and a raw namespace satisfies neither
  // once `strict` is on.
  ...blocks.map(({ category, subcategory, slug }) => {
    const name = `${category}-${subcategory}-${slug}`
    const importPath = `@/registry/${category}/${subcategory}/${slug}`
    return `  ${JSON.stringify(name)}: dynamic(() => import('${importPath}').then((m) => ({ default: m.default }))),`
  }),
  '}',
  '',
  `/** ${blocks.length} block${blocks.length === 1 ? '' : 's'} at generation time. */`,
  `export const BLOCK_COUNT: number = ${blocks.length}`,
  '',
]

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, lines.join('\n'))
console.log(`generated block-map.ts with ${blocks.length} block(s)`)

// Cross-check the catalogue: a block listed there with no file on disk would be
// advertised and then 404, which is the failure the old registry shipped.
const catalog = fs.readFileSync(path.join(registryDir, 'catalog.ts'), 'utf8')
const onDisk = new Set(blocks.map((b) => `${b.category}/${b.subcategory}/${b.slug}`))
const declared = [...catalog.matchAll(/slug:\s*'([a-z0-9-]+)'/g)].map((m) => m[1])
const orphans = blocks.filter((b) => !declared.includes(b.slug))
if (orphans.length) {
  console.warn(
    `WARNING: ${orphans.length} block file(s) not listed in catalog.ts: ${orphans
      .map((b) => `${b.category}/${b.subcategory}/${b.slug}`)
      .join(', ')}`,
  )
}
console.log(`${onDisk.size} block file(s) on disk`)
